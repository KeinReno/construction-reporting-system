import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';

type Credentials={manager_login:string;manager_password:string};
const path=process.env.OWNER_CREDENTIAL_FILE;
test.skip(!path || !process.env.OWNER_DEMO_URL,'Requires a private local owner demo');

async function signIn(page:import('@playwright/test').Page) {
  const credential=JSON.parse(readFileSync(path!,'utf8')) as Credentials;
  await page.goto('/');
  await page.getByLabel('Логин').fill(credential.manager_login);
  await page.getByLabel('Пароль').fill(credential.manager_password);
  await page.getByRole('button',{name:'Войти'}).click();
  await expect(page.getByRole('heading',{name:'Сводка архива'})).toBeVisible();
  return credential;
}


import { test,expect } from '@playwright/test';
test('Android-created report persists through real API into Web and review',async({page})=>{
  await page.goto('/');
  await page.getByLabel('Логин',{exact:true}).fill('manager');
  await page.getByLabel('Пароль',{exact:true}).fill('SyntheticPassword123');
  await page.getByRole('button',{name:'Войти',exact:true}).click();
  await expect(page.getByText('2.25 m',{exact:true})).toBeVisible();
  await page.getByRole('region',{name:'Объекты и отчёты'}).getByRole('button',{name:/Открыть отчёт за/}).first().click();
  const report=page.getByRole('region',{name:'Просмотр отчёта'});
  await expect(report.getByText('Corrected synthetic comment',{exact:true})).toBeVisible();
  await expect(report.getByText('Synthetic crew',{exact:true})).toBeVisible();
  await expect(report.getByText('Synthetic material',{exact:true})).toBeVisible();
  await expect(report.getByText(/Израсходовано · 1.5 m/)).toBeVisible();
  await expect(report.getByText('Synthetic incident',{exact:true})).toBeVisible();
  await expect(report.getByText(/Synthetic fuel/)).toBeVisible();
  await expect(report.getByText(/Synthetic crane/)).toBeVisible();
  await expect(report.getByText('Check access')).toBeVisible();
  await expect(report.getByText('Статус: Доставлен · ревизия 2')).toBeVisible();
  await expect(report.locator('img')).toHaveJSProperty('naturalWidth',2);
  await expect(report.locator('li').filter({hasText:'Доставлен'})).toHaveCount(2);
  await report.getByRole('button',{name:'Проверен',exact:true}).click();
  await expect(report.getByText('Статус: Проверен · ревизия 2')).toBeVisible();
  await report.getByRole('button',{name:'← Назад'}).click();
  await page.locator('.sidebar').getByRole('button',{name:'Помощник',exact:true}).click();
  const ai=page.getByRole('region',{name:'Аналитический центр CRS'});
  await ai.getByRole('button',{name:/Сформировать сводку/}).click();
  await expect(ai.locator('.crs-ai-answer-text')).toContainText('Получено отчётов: 1. Без работ: 0.');
  await ai.getByRole('button',{name:'Отчёт 1',exact:true}).click();
  await expect(page.getByRole('region',{name:'Просмотр отчёта'}).getByText('Статус: Проверен · ревизия 2')).toBeVisible();
});

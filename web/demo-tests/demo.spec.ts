import {test,expect} from '@playwright/test';
test('downloaded demo opens six examples, protected images, review and analytics',async({page})=>{
 await page.setViewportSize({width:1440,height:1000});
 page.on('pageerror',e=>console.log('BROWSER ERROR',e.message));
 page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE ERROR',m.text());});
 const info=await page.request.get('/demo-info');console.log('DEMO INFO',info.status(),(await info.text()).slice(0,150));
 await page.goto('/');
 console.log('ROOT',await page.title());
 await page.getByRole('button',{name:'Открыть демо: Руководитель',exact:true}).click();
 await expect(page.locator('.topbar-right')).toContainText('Руководитель (демо)');
 await expect(page.getByText('8.5 м',{exact:true})).toBeVisible();
 const home=page.getByRole('region',{name:'Объекты и отчёты'});
 await expect(home.getByRole('button',{name:/Открыть отчёт за/})).toHaveCount(6);
 await expect(home.locator('.owner-snapshot-item').filter({hasText:'Получено отчётов'}).locator('strong')).toHaveText('6');
 await home.getByRole('button',{name:/^Открыть отчёт за 22\/05\/2026/}).click();
 await expect(page.getByRole('region',{name:'Просмотр отчёта'}).getByText('Автор в системе: Бригадир (демо)')).toBeVisible();
 await expect(page.getByRole('region',{name:'Просмотр отчёта'}).getByText('Учебная бригада №1')).toBeVisible();
 await expect(page.getByRole('region',{name:'Просмотр отчёта'}).getByText('Учебный материал')).toBeVisible();
 await expect(page.getByRole('region',{name:'Просмотр отчёта'}).getByText('Учебное событие: временная задержка доступа.')).toBeVisible();
 await page.getByRole('region',{name:'Просмотр отчёта'}).getByRole('button',{name:'← Назад'}).click();
 await page.screenshot({path:'test-results/screenshots/web-01-overview.png',animations:'disabled'});
 await home.getByRole('button',{name:/^Открыть отчёт за 15\/05\/2026/}).click();
 const dialog=page.getByRole('region',{name:'Просмотр отчёта'});
 await expect(dialog.getByText(/Ручная покраска/)).toBeVisible();
 await expect(dialog.locator('img')).toHaveJSProperty('naturalWidth',800);
 await page.screenshot({path:'test-results/screenshots/web-02-report.png',animations:'disabled'});
 await dialog.getByRole('button',{name:'← Назад'}).click();
 await page.getByRole('button',{name:'Готовые сводки',exact:true}).first().click();
 await page.getByLabel('Вид анализа').selectOption('auto');
 await page.getByLabel('Вопрос (сохраняется только на экране)').fill('Какие простои повторяются?');
 await page.getByRole('button',{name:'Сформировать анализ'}).click();
 await expect(page.getByRole('button',{name:'Отчёт 3',exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/screenshots/web-03-analytics.png',fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Отчёт 3',exact:true}).click();
 await expect(page.getByRole('region',{name:'Просмотр отчёта'}).getByText(/Бригада прибыла, но не получила допуск/)).toBeVisible();
 await page.getByRole('region',{name:'Просмотр отчёта'}).getByRole('button',{name:'Проверен',exact:true}).click();
 await expect(page.getByRole('region',{name:'Просмотр отчёта'}).getByText('Статус: Проверен · ревизия 1')).toBeVisible();
 await page.getByRole('region',{name:'Просмотр отчёта'}).getByRole('button',{name:'← Назад'}).click();
 await page.getByRole('button',{name:'Выйти',exact:true}).click();
 await page.getByRole('button',{name:'Открыть демо: Администратор',exact:true}).click();
 await page.getByRole('button',{name:'Управление',exact:true}).first().click();
 await expect(page.getByRole('heading',{name:'Пользователи',exact:true})).toBeVisible();
 await expect(page.getByRole('cell',{name:'demo-manager',exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/screenshots/web-04-admin.png',fullPage:true,animations:'disabled'});
});

const {chromium}=require('../../../web/node_modules/@playwright/test');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:390,height:900},reducedMotion:'reduce'});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:58515/#app/form');
 await page.evaluate(()=>localStorage.clear());
 await page.reload();
 await page.locator('[data-field="catalog"]').first().selectOption({label:'Прокладка кабеля'});
 await page.waitForTimeout(200);
 if(await page.locator('[data-field="unit"]').first().inputValue()!=='м') throw Error('unit did not follow work type');
 if(await page.locator('[name="quantity"]').inputValue()!=='') throw Error('quantity stayed after unit change');
 await page.locator('#add-work').click();
 await page.waitForTimeout(200);
 if(await page.locator('[data-field="unit"]').nth(1).inputValue()!=='шт') throw Error('new row inherited previous unit');
 await page.locator('[data-field="catalog"]').nth(1).selectOption({label:'Уборка территории'});
 await page.waitForTimeout(200);
 const second=await page.locator('.work-row').nth(1).innerText();
 if(!second.includes('Без численного объёма')) throw Error('qualitative row still asks for a number');
 await page.locator('[data-field="catalog"]').nth(1).selectOption({label:'Другое'});
 await page.locator('[name="crewConfirmed"]').check();
 await page.getByRole('button',{name:'Проверить отчёт'}).click();
 await page.waitForTimeout(200);
 if(!page.url().endsWith('app/form')) throw Error('other without explanation was accepted');
 if(!(await page.locator('#form-error').innerText()).includes('Другое')) throw Error('missing other message');
 const size=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
 if(size.scroll>size.client) throw Error('form overflow '+JSON.stringify(size));
 if(errors.length) throw Error(errors.join(';'));
 console.log('PASS several works, units and qualitative rows');
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
